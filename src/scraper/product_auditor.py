from datetime import datetime
import numpy as np
import pandas as pd
import joblib

from src.scraper.review_parser import ReviewParser
from src.evaluation.explainer import TreeSHAPExplainer, FEATURE_FRIENDLY_NAMES
from src.features.behavioral import RobustSentimentAnalyzer


AI_LEAK_PATTERNS = [
    (r"\bas an ai language model\b", "Explicit LLM Self-Disclosure ('As an AI language model')"),
    (r"\bas an ai\b", "Explicit AI Identity Assertion"),
    (r"\bas a (?:large )?language model\b", "LLM Disclaimer Leak"),
    (r"\bi (?:do not|don't) have a (?:biological|physical) (?:throat|body|mouth|form)\b", "Synthetic Non-Biological Disclosure"),
    (r"\b100% genuine honest review as a real human\b", "Synthetic 'Real Human' Identity Assertion"),
    (r"\bas a real human consumer\b", "Unnatural Synthetic Human Persona Assertion"),
    (r"\bi am an artificial intelligence\b", "Explicit AI Identity Assertion"),
    (r"\bgenerated by (?:chatgpt|gpt-4|gemini|claude|llm)\b", "Generator Metadata Leak"),
]


def detect_synthetic_ai_leak(text: str) -> Optional[str]:
    """Detects explicit AI / LLM leaks and self-disclosures in review text."""
    if not isinstance(text, str):
        return None
    for pat, desc in AI_LEAK_PATTERNS:
        if re.search(pat, text, re.IGNORECASE):
            return desc
    return None


# Resolve root directory dynamically
DEFAULT_BASE_DIR = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))


class ProductAuditor:
    """Audits live e-commerce product links, extracts reviews, and renders fraud verdicts."""

    def __init__(self, base_dir: Optional[str] = None):
        self.base_dir = base_dir or DEFAULT_BASE_DIR
        self.parser = ReviewParser()
        self.sentiment_analyzer = RobustSentimentAnalyzer()

        # Load serialized pipeline and model artifacts
        model_path = os.path.join(base_dir, "artifacts/models/fused_xgboost_model.joblib")
        scaler_path = os.path.join(base_dir, "artifacts/scalers/feature_pipeline.joblib")
        calib_path = os.path.join(base_dir, "artifacts/calibrators/isotonic_calibrator.joblib")

        self.model = joblib.load(model_path) if os.path.exists(model_path) else None
        self.pipeline = joblib.load(scaler_path) if os.path.exists(scaler_path) else None
        self.calibrator = joblib.load(calib_path) if os.path.exists(calib_path) else None
        self.explainer = TreeSHAPExplainer(self.model, self.pipeline.feature_names) if self.model and self.pipeline else None

    def fetch_live_reviews_firecrawl(self, product_url: str) -> Tuple[List[Dict[str, Any]], str]:
        """Scrapes product link using Firecrawl API."""
        api_key = os.environ.get("FIRECRAWL_API_KEY")
        if not api_key:
            key_file = os.path.expanduser("~/.firecrawl_api_key")
            if os.path.exists(key_file):
                with open(key_file, "r") as f:
                    api_key = f.read().strip()

        if not api_key:
            return [], "Firecrawl API key not found in ~/.firecrawl_api_key"

        try:
            from firecrawl.v1.client import V1FirecrawlApp
            app = V1FirecrawlApp(api_key=api_key)
            scrape_res = app.scrape_url(product_url, formats=["markdown"])

            markdown = ""
            if hasattr(scrape_res, "markdown") and scrape_res.markdown:
                markdown = scrape_res.markdown
            elif isinstance(scrape_res, dict):
                markdown = scrape_res.get("markdown", "")

            # If robot check or captcha page returned by target
            if "captcha" in markdown.lower() or "robot check" in markdown.lower() or len(markdown) < 100:
                return [], "Target retailer returned anti-bot challenge / CAPTCHA"

            parsed = self.parser.parse_markdown_reviews(markdown, product_url)
            if len(parsed) >= 2:
                return parsed, f"Scraped {len(parsed)} reviews directly from destination"
            elif len(parsed) == 1:
                return parsed, "Only 1 review found on page"
            else:
                return [], "Page scraped, but no review blocks matched parser patterns"
        except Exception as e:
            return [], f"Scraping connection error: {str(e)}"

    def audit_url(
        self,
        product_url: str,
        product_name: str = "Target E-Commerce Item",
        profile: Optional[str] = None,
        custom_reviews: Optional[List[Dict[str, Any]]] = None,
    ) -> Dict[str, Any]:
        """Audits a product URL or custom review batch: extracts reviews, classifies them, and produces trust report."""
        if self.model is None or self.pipeline is None:
            raise RuntimeError("Model artifacts must be trained before auditing.")

        is_simulated = False
        reviews = []
        scrape_status = ""

        if custom_reviews and len(custom_reviews) > 0:
            reviews = custom_reviews
            scrape_status = f"Analyzed {len(reviews)} custom reviews provided by user."
        elif profile is not None:
            # Explicit profile requested by preset button (Grade A, B, C, D, F)
            is_simulated = True
            reviews = self.parser.generate_simulated_product_feed(product_url, product_name, profile=profile)
            scrape_status = f"Preset test benchmark profile '{profile}'."
        else:
            # 1. Scrape live reviews
            live_reviews, scrape_msg = self.fetch_live_reviews_firecrawl(product_url)

            # Fallback to simulation if site actively blocks scraping / empty
            if len(live_reviews) < 2:
                is_simulated = True
                reviews = self.parser.generate_simulated_product_feed(product_url, product_name, profile=None)
                scrape_status = f"Live scraping unaccessible ({scrape_msg}). Evaluated URL-hashed test profile."
            else:
                reviews = live_reviews
                scrape_status = scrape_msg

        df = pd.DataFrame(reviews)
        if len(df) == 0:
            df = pd.DataFrame([{"text": "No reviews found", "rating": 5, "reviewer_id": "u1", "product_id": "p1", "date": datetime.now()}])

        if "text" not in df.columns:
            df["text"] = ""
        df["text"] = df["text"].fillna("").astype(str)

        if "rating" not in df.columns:
            df["rating"] = 5
        df["rating"] = pd.to_numeric(df["rating"], errors="coerce").fillna(5).astype(int)

        if "reviewer_id" not in df.columns:
            df["reviewer_id"] = [f"buyer_{i+1:02d}" for i in range(len(df))]
        df["reviewer_id"] = df["reviewer_id"].fillna("verified_buyer")

        if "product_id" not in df.columns:
            df["product_id"] = "prod_target"
        df["product_id"] = df["product_id"].fillna("prod_target")

        if "date" not in df.columns:
            from datetime import timedelta
            df["date"] = [datetime.now() - timedelta(days=i * 2 + 1) for i in range(len(df))]
        df["date"] = pd.to_datetime(df["date"].fillna(datetime.now()))

        # 2. Extract features and predict with local batch context
        X, _ = self.pipeline.transform(df, update_context=True)
        raw_probs = self.model.predict_proba(X)
        calibrated_probs = self.calibrator.predict_proba(raw_probs) if self.calibrator else raw_probs

        # 3. Calculate per-review metrics
        scored_reviews = []
        fake_count = 0
        suspicious_count = 0
        genuine_count = 0

        weighted_rating_sum = 0.0
        total_weight = 0.0

        for idx, row in df.iterrows():
            prob = float(calibrated_probs[idx])
            rating = int(row["rating"])
            text = row["text"]

            ai_leak = detect_synthetic_ai_leak(text)
            if ai_leak:
                prob = 1.0

            # Mismatch calculation
            c_t = self.sentiment_analyzer.polarity_score(text)
            s_hat = (rating - 3.0) / 2.0
            mismatch_val = abs(s_hat - c_t)
            mismatch_flag = mismatch_val > 0.60

            # Risk tier and trust weights
            if prob < 0.40:
                risk_tier = "Genuine"
                genuine_count += 1
                w = 1.0
            elif prob < 0.70:
                risk_tier = "Suspicious"
                suspicious_count += 1
                w = 0.5
            else:
                risk_tier = "Likely Fake"
                fake_count += 1
                w = 0.0

            weighted_rating_sum += w * rating
            total_weight += w

            # Top SHAP explanation or AI leak reason
            if ai_leak:
                top_reason = f"🤖 AI Self-Disclosure ({ai_leak})"
            else:
                exps = self.explainer.explain_instance(X[idx], top_k=2) if self.explainer else []
                top_reason = exps[0]["friendly_name"] if exps else "Linguistic & Metadata Pattern"

            scored_reviews.append({
                "rating": rating,
                "reviewer": row["reviewer_id"],
                "fake_probability": prob,
                "risk_tier": risk_tier,
                "mismatch_flag": mismatch_flag,
                "top_reason": top_reason,
                "text": text,
            })

        # 4. Aggregated Product Integrity Metrics
        total_revs = len(scored_reviews)
        fake_share = (fake_count / total_revs) if total_revs > 0 else 0.0
        suspicious_share = (suspicious_count / total_revs) if total_revs > 0 else 0.0

        raw_avg_rating = float(df["rating"].mean())
        # Calculate Adjusted Rating (discounting manipulated reviews)
        if total_weight > 0:
            adjusted_rating = float(weighted_rating_sum / total_weight)
        else:
            adjusted_rating = raw_avg_rating

        # Assign Letter Grade (A to F)
        if fake_share < 0.10 and suspicious_share < 0.15:
            trust_grade = "A (High Trust)"
            grade_color = "#2ec4b6"
            verdict_text = "Reviews appear predominantly authentic and organic."
        elif fake_share < 0.25:
            trust_grade = "B (Good)"
            grade_color = "#3a86ff"
            verdict_text = "Mostly genuine reviews with isolated marketing stock phrasing."
        elif fake_share < 0.40:
            trust_grade = "C (Caution)"
            grade_color = "#f4a261"
            verdict_text = "Noticeable presence of incentivized reviews or rating mismatches."
        elif fake_share < 0.60:
            trust_grade = "D (High Risk)"
            grade_color = "#e76f51"
            verdict_text = "Substantial evidence of coordinated Sybil review bursts and deception."
        else:
            trust_grade = "F (Severe Manipulation)"
            grade_color = "#e63946"
            verdict_text = "Heavily manipulated listing; majority of reviews appear automated or fake."

        return {
            "product_url": product_url,
            "product_name": product_name,
            "is_simulated": is_simulated,
            "scrape_status": scrape_status,
            "total_reviews_audited": total_revs,
            "fake_review_count": fake_count,
            "suspicious_review_count": suspicious_count,
            "genuine_review_count": genuine_count,
            "fake_review_percentage": fake_share,
            "reported_star_rating": raw_avg_rating,
            "adjusted_true_star_rating": adjusted_rating,
            "trust_grade": trust_grade,
            "grade_color": grade_color,
            "verdict_summary": verdict_text,
            "reviews_table": pd.DataFrame(scored_reviews),
        }
